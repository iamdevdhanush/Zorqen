"""ZORQEN — Tests for GitHub permissions, least privilege, and OAuth CSRF validation.

Proves:
1. Mutating operations (create_branch, create_or_update_file, create_pull_request)
   are disabled and raise PermissionError.
2. OAuth CSRF state is cryptographically signed, time-bound, and verifiable across
   multiple worker processes without shared in-memory dictionaries.
3. Tampered, expired, or invalid OAuth states are rejected.
4. Required permissions and scopes are verified.
"""
import pytest
from datetime import datetime, timedelta, timezone
from unittest.mock import AsyncMock, patch
from jose import jwt

from core.config import settings
from github.client import GitHubClient
from github.oauth import (
    GITHUB_SCOPES,
    REQUIRED_GITHUB_SCOPES,
    get_oauth_redirect_url,
    missing_required_scopes,
)
from routers.auth import generate_oauth_state, validate_oauth_state, _oauth_states


@pytest.mark.asyncio
async def test_github_client_create_branch_disabled():
    client = GitHubClient(access_token="test-token")
    with pytest.raises(PermissionError) as exc_info:
        await client.create_branch("owner", "repo", "test-branch", "sha123")
    assert "Write operations are disabled" in str(exc_info.value)


@pytest.mark.asyncio
async def test_github_client_create_or_update_file_disabled():
    client = GitHubClient(access_token="test-token")
    with pytest.raises(PermissionError) as exc_info:
        await client.create_or_update_file(
            "owner", "repo", "test.py", "Commit msg", "print(1)", "main"
        )
    assert "Write operations are disabled" in str(exc_info.value)


