def test_stateless_oauth_csrf_state_generation_and_validation():
    """State generated by one worker must be valid for another worker sharing secret_key."""
    state = generate_oauth_state()
    assert isinstance(state, str)
    assert len(state) > 20
    # Validate token
    assert validate_oauth_state(state) is True


def test_oauth_csrf_state_rejects_expired():
    """Expired state tokens must be rejected."""
    now = datetime.now(timezone.utc)
    expired_payload = {
        "nonce": "test-nonce",
        "purpose": "github_oauth_csrf",
        "iat": int((now - timedelta(minutes=30)).timestamp()),
        "exp": int((now - timedelta(minutes=15)).timestamp()),
    }
    expired_state = jwt.encode(expired_payload, settings.secret_key, algorithm=settings.jwt_algorithm)
    assert validate_oauth_state(expired_state) is False


def test_oauth_csrf_state_rejects_tampered():
    """State signed with an invalid or different key must be rejected."""
    tampered_payload = {
        "nonce": "test-nonce",
        "purpose": "github_oauth_csrf",
        "exp": int((datetime.now(timezone.utc) + timedelta(minutes=10)).timestamp()),
    }
    tampered_state = jwt.encode(tampered_payload, "wrong-secret-key-12345", algorithm="HS256")
    assert validate_oauth_state(tampered_state) is False


def test_oauth_csrf_state_rejects_wrong_purpose():
    """Tokens not designated for OAuth CSRF must be rejected."""
    wrong_payload = {
        "nonce": "test-nonce",
        "purpose": "user_session",
        "exp": int((datetime.now(timezone.utc) + timedelta(minutes=10)).timestamp()),
    }
    wrong_state = jwt.encode(wrong_payload, settings.secret_key, algorithm=settings.jwt_algorithm)
    assert validate_oauth_state(wrong_state) is False


def test_oauth_csrf_state_empty_or_none():
    assert validate_oauth_state(None) is False
    assert validate_oauth_state("") is False
    assert validate_oauth_state("invalid-random-string") is False


def test_oauth_csrf_state_backwards_compatibility():
    """_oauth_states dict fallback works for legacy tests."""
    _oauth_states["legacy-mock-state"] = "pending"
    assert validate_oauth_state("legacy-mock-state") is True
    # Consumed
    assert "legacy-mock-state" not in _oauth_states


def test_oauth_scopes_and_redirect_url():
    state = "test-state-123"
    url = get_oauth_redirect_url(state)
    assert "state=test-state-123" in url
    assert "scope=" in url
    assert "repo" in url

    # Scope validation
    assert missing_required_scopes(["repo", "read:user", "user:email"]) == []
    assert missing_required_scopes(["read:user"]) == ["repo", "user:email"]
