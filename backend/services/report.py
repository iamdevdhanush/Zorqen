"""ZORQEN — Enterprise Security Validation Report (PDF)

Renders "Security Validation Report.pdf" with reportlab in a clean
black / white / lime brutalist design:

  Cover        — ZORQEN branding, repository, commit, assessment ID
  Executive    — summary of the run
  Security     — posture score
  Severity     — breakdown by severity class
  Architecture — overview (languages, frameworks, entrypoints, routes)
  Attack       — surface (inputs, sinks, endpoints, dependencies)
  Findings     — table with severity / CWE / file / line / explanation /
                 remediation per finding
  Timeline     — stage timestamps of the run
  Footer       — "Generated by ZORQEN Security Validation." on every page
"""
from __future__ import annotations

import io
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

import structlog
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from models.assessment import Assessment
from models.finding import Finding

log = structlog.get_logger()

LIME = colors.HexColor("#C5F82A")
BLACK = colors.HexColor("#111111")
WHITE = colors.white
GRAY = colors.HexColor("#5E5E5E")
LIGHT = colors.HexColor("#F5F5F0")

SEVERITY_COLORS = {
    "critical": colors.HexColor("#FF3B3B"),
    "high": colors.HexColor("#FF6B00"),
    "medium": colors.HexColor("#F5B800"),
    "low": colors.HexColor("#1D4ED8"),
    "info": GRAY,
}

# Fallback remediation guidance keyed by CWE / vulnerability type — used when
# an AI-generated fix has not been produced for a finding.
_REMEDIATION_GUIDANCE: Dict[str, str] = {
    "CWE-89": "Parameterize all SQL queries using prepared statements or an ORM; never concatenate user input into SQL strings.",
    "CWE-79": "Escape all dynamic output and adopt a strict Content Security Policy; prefer safe template auto-escaping.",
    "CWE-78": "Avoid shell=True and os.system(); use subprocess with explicit argument lists and validate/allowlist input.",
    "CWE-22": "Validate and canonicalize user-supplied paths; confine file access to an allowlisted base directory.",
    "CWE-918": "Restrict outbound requests to an allowlist of hosts and validate scheme/host before issuing requests.",
    "CWE-798": "Remove the credential from source and load it from a secret manager / environment variable at runtime.",
    "CWE-256": "Never store plaintext secrets in code; migrate to a managed secret store and rotate exposed credentials.",
    "CWE-321": "Move cryptographic keys to a key management service; never hardcode keys in source or config.",
    "CWE-502": "Avoid deserializing untrusted data; if required, use a safe format and validate payloads before use.",
    "CWE-338": "Use secrets.token_* or secrets.SystemRandom for security-sensitive random values; never random.random().",
    "CWE-306": "Require authentication on every state-changing endpoint; apply auth middleware or decorators globally.",
    "CWE-862": "Enforce authorization checks on all resources; verify the actor owns or may access the object.",
    "CWE-639": "Replace user-supplied object IDs with session-derived references and enforce ownership checks.",
    "CWE-942": "Restrict CORS to explicit trusted origins and methods; never reflect credentials with a wildcard.",
    "CWE-693": "Add security headers (CSP, X-Frame-Options, HSTS, X-Content-Type-Options) via middleware.",
    "CWE-522": "Transmit credentials only over TLS and store them encrypted; rotate any exposed credentials.",
}


def _utcnow_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def _finding_explanation(finding: Finding) -> str:
    parts = []
    if finding.root_cause:
        parts.append(f"Root cause: {finding.root_cause}")
    if finding.impact:
        parts.append(f"Impact: {finding.impact}")
    if finding.ai_reasoning:
        parts.append(finding.ai_reasoning)
    if finding.evidence:
        parts.append(f"Evidence: {finding.evidence}")
    if not parts:
        return "No detailed explanation available for this finding."
    return " ".join(parts)


def _finding_remediation(finding: Finding) -> str:
    remediation = finding.remediation
    if remediation and remediation.explanation:
        return remediation.explanation
    if finding.cwe_id and finding.cwe_id in _REMEDIATION_GUIDANCE:
        return _REMEDIATION_GUIDANCE[finding.cwe_id]
    if finding.vulnerability_type:
        lowered = finding.vulnerability_type.lower()
        for cwe, guidance in _REMEDIATION_GUIDANCE.items():
            if cwe in lowered:
                return guidance
    return (
        "Review the affected code path, validate and sanitize all external "
        "input, and apply defense-in-depth controls (least privilege, "
        "allowlists, secure defaults)."
    )


# ── Styles ──────────────────────────────────────────────────────────────────

def _build_styles():
    base = getSampleStyleSheet()
    styles = {
        "cover_title": ParagraphStyle(
            "cover_title", parent=base["Title"], fontName="Helvetica-Bold",
            fontSize=44, leading=50, textColor=BLACK, alignment=TA_CENTER,
        ),
        "cover_sub": ParagraphStyle(
            "cover_sub", parent=base["Normal"], fontName="Helvetica-Bold",
            fontSize=12, leading=16, textColor=BLACK, alignment=TA_CENTER,
        ),
        "h1": ParagraphStyle(
            "h1", parent=base["Heading1"], fontName="Helvetica-Bold",
            fontSize=18, leading=22, textColor=BLACK, spaceAfter=4,
        ),
        "h2": ParagraphStyle(
            "h2", parent=base["Heading2"], fontName="Helvetica-Bold",
            fontSize=12, leading=16, textColor=BLACK, spaceBefore=8, spaceAfter=2,
        ),
        "body": ParagraphStyle(
            "body", parent=base["BodyText"], fontName="Helvetica",
            fontSize=9.5, leading=13.5, textColor=BLACK, spaceAfter=6,
        ),
        "muted": ParagraphStyle(
            "muted", parent=base["BodyText"], fontName="Helvetica",
            fontSize=8.5, leading=12, textColor=GRAY,
        ),
        "small_bold": ParagraphStyle(
            "small_bold", parent=base["BodyText"], fontName="Helvetica-Bold",
            fontSize=8, leading=11, textColor=BLACK,
        ),
        "cell": ParagraphStyle(
            "cell", parent=base["BodyText"], fontName="Helvetica",
            fontSize=7.5, leading=10, textColor=BLACK,
        ),
        "cell_bold": ParagraphStyle(
            "cell_bold", parent=base["BodyText"], fontName="Helvetica-Bold",
            fontSize=7.5, leading=10, textColor=BLACK,
        ),
        "score": ParagraphStyle(
            "score", parent=base["Title"], fontName="Helvetica-Bold",
            fontSize=42, leading=48, textColor=BLACK, alignment=TA_CENTER,
        ),
    }
    return styles


def _section_header(title: str, styles: Dict[str, ParagraphStyle], number: int):
    """Brutalist section header: black bar + lime index block."""
    bar = Table(
        [
            [
                Paragraph(f"{number:02d}", styles["cell_bold"]),
                Paragraph(title.upper(), styles["cell_bold"]),
            ]
        ],
        colWidths=[14 * mm, None],
    )
    bar.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, 0), LIME),
        ("BACKGROUND", (1, 0), (1, 0), BLACK),
        ("TEXTCOLOR", (1, 0), (1, 0), WHITE),
        ("TEXTCOLOR", (0, 0), (0, 0), BLACK),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    return [Spacer(1, 10 * mm), bar, Spacer(1, 4 * mm)]


def _footer(canvas, doc):
    """Fixed footer with the ZORQEN attribution on every page."""
    canvas.saveState()
    canvas.setStrokeColor(BLACK)
    canvas.setLineWidth(0.75)
    canvas.line(16 * mm, 13 * mm, A4[0] - 16 * mm, 13 * mm)
    canvas.setFont("Helvetica", 7)
    canvas.setFillColor(GRAY)
    canvas.drawString(16 * mm, 9.5 * mm, "Generated by ZORQEN Security Validation.")
    canvas.drawRightString(A4[0] - 16 * mm, 9.5 * mm, f"Page {doc.page}")
    canvas.restoreState()


def build_report_pdf(
    assessment: Assessment,
    findings: List[Finding],
    repository: Any,
    *,
    generated_at: Optional[str] = None,
) -> bytes:
    """Render the full report as PDF bytes.

    `repository` is the Repository ORM object; only display metadata is
    read. `findings` must be the assessment's findings, pre-loaded with
    `remediation` when available.
    """
    styles = _build_styles()
    buffer = io.BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=16 * mm,
        rightMargin=16 * mm,
        topMargin=16 * mm,
        bottomMargin=18 * mm,
        title="Security Validation Report",
        author="ZORQEN",
    )

    run_id = f"#{assessment.run_number:04d}" if assessment.run_number else assessment.id[:8].upper()
    repo_name = repository.full_name if repository and getattr(repository, "full_name", None) else (
        repository.name if repository else "unknown"
    )
    commit_short = (assessment.commit_sha or "")[:7] or (getattr(repository, "head_commit", None) or "")[:7] or "HEAD"
    started_at = assessment.started_at.strftime("%Y-%m-%d %H:%M UTC") if assessment.started_at else "—"
    completed_at = assessment.completed_at.strftime("%Y-%m-%d %H:%M UTC") if assessment.completed_at else "—"
    generated_at = generated_at or _utcnow_iso()
    score = round(assessment.security_score or 0)

    counts = {
        "critical": assessment.critical_count or 0,
        "high": assessment.high_count or 0,
        "medium": assessment.medium_count or 0,
        "low": assessment.low_count or 0,
    }

    arch = assessment.architecture_map or {}
    intel = arch.get("repo_intel") or {}
    languages = intel.get("languages") or {}
    frameworks = intel.get("frameworks") or []
    entrypoints = intel.get("entrypoints") or []
    routes = intel.get("routes") or []
    inputs = intel.get("input_sources") or []
    sinks = intel.get("sinks") or []
    dependencies = intel.get("dependencies") or []
    db_engines = intel.get("db_engines") or []
    integrations = intel.get("integrations") or []

    story: List[Any] = []

    # ── Cover ───────────────────────────────────────────────────────────────
    story.append(Spacer(1, 30 * mm))
    cover_band = Table(
        [[Paragraph("ZORQEN", styles["cover_title"])]],
        colWidths=[A4[0] - 32 * mm],
    )
    cover_band.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), LIME),
        ("TOPPADDING", (0, 0), (-1, -1), 14),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 14),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
    ]))
    story.append(cover_band)
    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph("SECURITY VALIDATION REPORT", styles["cover_sub"]))
    story.append(Spacer(1, 22 * mm))

    cover_meta = Table(
        [
            ["REPOSITORY", repo_name],
            ["COMMIT", commit_short],
            ["BRANCH", assessment.branch or "main"],
            ["ASSESSMENT ID", run_id],
            ["GENERATED", generated_at],
        ],
        colWidths=[45 * mm, None],
    )
    cover_meta.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTNAME", (1, 0), (1, -1), "Helvetica"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (0, -1), GRAY),
        ("TEXTCOLOR", (1, 0), (1, -1), BLACK),
        ("LINEBELOW", (0, 0), (-1, -2), 0.75, BLACK),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(cover_meta)
    story.append(Spacer(1, 30 * mm))
    story.append(Paragraph("AI-Powered Autonomous Security Validation", styles["muted"]))
    story.append(PageBreak())

    # ── 01 Executive Summary ────────────────────────────────────────────────
    story.extend(_section_header("Executive Summary", styles, 1))
    total_findings = sum(counts.values())
    run_status = getattr(assessment.status, "value", assessment.status) or "pending"
    if run_status == "completed":
        summary = (
            f"ZORQEN validated <b>{repo_name}</b> at commit <b>{commit_short}</b> "
            f"on branch <b>{assessment.branch or 'main'}</b>. The repository received a "
            f"security score of <b>{score}/100</b>. The scan produced <b>{total_findings}</b> "
            f"finding(s): {counts['critical']} critical, {counts['high']} high, "
            f"{counts['medium']} medium and {counts['low']} low."
        )
    elif run_status == "failed":
        summary = (
            f"The validation of <b>{repo_name}</b> at commit <b>{commit_short}</b> did not "
            f"complete. {assessment.error_message or 'The pipeline failed without a recorded reason.'}"
        )
    else:
        summary = f"The validation of <b>{repo_name}</b> at commit <b>{commit_short}</b> is in progress."
    story.append(Paragraph(summary, styles["body"]))
    ai_note = arch.get("ai_summary") or ""
    if not ai_note and assessment.error_code:
        ai_note = f"Pipeline note: {assessment.error_code}."
    if ai_note:
        story.append(Paragraph(ai_note, styles["muted"]))
    story.append(Paragraph(
        f"Assessment {run_id} · started {started_at} · completed {completed_at}.",
        styles["muted"],
    ))
    story.append(PageBreak())

    # ── 02 Security Score ───────────────────────────────────────────────────
    story.extend(_section_header("Security Score", styles, 2))
    score_grade = (
        "STRONG SECURITY POSTURE" if score >= 80
        else "MODERATE SECURITY POSTURE" if score >= 60
        else "HIGH RISK SURFACE"
    )
    score_table = Table(
        [
            [Paragraph(f"{score}", styles["score"])],
            [Paragraph("OUT OF 100", styles["small_bold"])],
            [Paragraph(score_grade, styles["small_bold"])],
        ],
        colWidths=[70 * mm],
    )
    score_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -2), LIME),
        ("BACKGROUND", (0, -1), (-1, -1), BLACK),
        ("TEXTCOLOR", (0, -1), (-1, -1), WHITE),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("BOX", (0, 0), (-1, -1), 1.5, BLACK),
    ]))
    story.append(score_table)

    # ── 03 Severity Breakdown ───────────────────────────────────────────────
    story.extend(_section_header("Severity Breakdown", styles, 3))
    severity_rows = [[
        Paragraph("SEVERITY", styles["cell_bold"]),
        Paragraph("COUNT", styles["cell_bold"]),
        Paragraph("ACTION REQUIRED", styles["cell_bold"]),
    ]]
    action_labels = {
        "critical": "Immediate remediation",
        "high": "Remediate this sprint",
        "medium": "Audit queue",
        "low": "Best practice",
    }
    for sev in ("critical", "high", "medium", "low"):
        severity_rows.append([
            Paragraph(sev.upper(), styles["cell_bold"]),
            Paragraph(str(counts[sev]), styles["cell"]),
            Paragraph(action_labels[sev], styles["cell"]),
        ])
    severity_table = Table(severity_rows, colWidths=[40 * mm, 30 * mm, None])
    severity_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BLACK),
        ("TEXTCOLOR", (0, 0), (-1, 0), WHITE),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [WHITE, LIGHT]),
        ("GRID", (0, 0), (-1, -1), 0.75, BLACK),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(severity_table)
    story.append(PageBreak())

    # ── 04 Architecture Overview ────────────────────────────────────────────
    story.extend(_section_header("Architecture Overview", styles, 4))
    arch_rows = [
        [Paragraph("LANGUAGES", styles["cell_bold"]), Paragraph(
            ", ".join(f"{k} ({v})" for k, v in list(languages.items())[:8]) or "—", styles["cell"])],
        [Paragraph("PRIMARY LANGUAGE", styles["cell_bold"]), Paragraph(
            intel.get("primary_language") or arch.get("primary_language") or "Unknown", styles["cell"])],
        [Paragraph("FRAMEWORKS", styles["cell_bold"]), Paragraph(
            ", ".join(frameworks) or "—", styles["cell"])],
        [Paragraph("ENTRYPOINTS", styles["cell_bold"]), Paragraph(
            "<br/>".join(entrypoints) or "—", styles["cell"])],
        [Paragraph("FILES", styles["cell_bold"]), Paragraph(
            str(intel.get("file_count", 0)), styles["cell"])],
        [Paragraph("DATABASE ENGINES", styles["cell_bold"]), Paragraph(
            ", ".join(db_engines) or "—", styles["cell"])],
        [Paragraph("EXTERNAL INTEGRATIONS", styles["cell_bold"]), Paragraph(
            ", ".join(integrations) or "—", styles["cell"])],
    ]
    arch_table = Table(arch_rows, colWidths=[50 * mm, None])
    arch_table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.75, BLACK),
        ("ROWBACKGROUNDS", (0, 0), (-1, -1), [WHITE, LIGHT]),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(arch_table)

    # ── 05 Attack Surface ───────────────────────────────────────────────────
    story.extend(_section_header("Attack Surface", styles, 5))
    surface_rows = [
        [Paragraph("ENDPOINTS / ROUTES", styles["cell_bold"]), Paragraph(str(len(routes)), styles["cell"])],
        [Paragraph("USER-CONTROLLED INPUTS", styles["cell_bold"]), Paragraph(str(len(inputs)), styles["cell"])],
        [Paragraph("DANGEROUS SINKS", styles["cell_bold"]), Paragraph(str(len(sinks)), styles["cell"])],
        [Paragraph("DEPENDENCIES", styles["cell_bold"]), Paragraph(str(len(dependencies)), styles["cell"])],
        [Paragraph("SECRETS EXPOSED", styles["cell_bold"]), Paragraph(
            str(assessment.secrets_count or 0), styles["cell"])],
    ]
    surface_table = Table(surface_rows, colWidths=[50 * mm, None])
    surface_table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.75, BLACK),
        ("ROWBACKGROUNDS", (0, 0), (-1, -1), [WHITE, LIGHT]),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(surface_table)
    if routes:
        story.append(Spacer(1, 4 * mm))
        story.append(Paragraph("TOP EXPOSED ROUTES", styles["h2"]))
        route_rows = [[
            Paragraph("METHOD", styles["cell_bold"]),
            Paragraph("ENDPOINT", styles["cell_bold"]),
            Paragraph("FILE", styles["cell_bold"]),
            Paragraph("AUTH", styles["cell_bold"]),
        ]]
        for route in routes[:8]:
            route_rows.append([
                Paragraph(str(route.get("method", "ANY")), styles["cell"]),
                Paragraph(str(route.get("endpoint", "")), styles["cell"]),
                Paragraph(str(route.get("file_path", "")), styles["cell"]),
                Paragraph(
                    "REQUIRED" if route.get("auth_required") else "UNKNOWN/MISSING",
                    styles["cell"],
                ),
            ])
        route_table = Table(route_rows, colWidths=[22 * mm, 52 * mm, None, 30 * mm])
        route_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), BLACK),
            ("TEXTCOLOR", (0, 0), (-1, 0), WHITE),
            ("GRID", (0, 0), (-1, -1), 0.5, BLACK),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(route_table)
    story.append(PageBreak())

    # ── 06 Findings ─────────────────────────────────────────────────────────
    story.extend(_section_header("Findings", styles, 6))
    if not findings:
        story.append(Paragraph(
            "No vulnerabilities were identified in the scanned surface.", styles["body"]))
    else:
        for idx, finding in enumerate(findings, start=1):
            sev = (finding.severity or "info").lower()
            sev_color = SEVERITY_COLORS.get(sev, GRAY)
            file_loc = f"{finding.file_path or '—'}:{finding.line_number or '—'}"
            confidence = finding.confidence_pct or 0
            header = Table(
                [
                    [
                        Paragraph(f"{idx:02d}", styles["cell_bold"]),
                        Paragraph(
                            f"{finding.vulnerability_type or finding.title}".upper(),
                            styles["cell_bold"],
                        ),
                        Paragraph(sev.upper(), styles["cell_bold"]),
                    ]
                ],
                colWidths=[12 * mm, None, 30 * mm],
            )
            header.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (0, 0), LIME),
                ("BACKGROUND", (1, 0), (1, 0), BLACK),
                ("TEXTCOLOR", (1, 0), (1, 0), WHITE),
                ("BACKGROUND", (2, 0), (2, 0), sev_color),
                ("TEXTCOLOR", (2, 0), (2, 0), WHITE),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LEFTPADDING", (0, 0), (-1, -1), 7),
            ]))
            story.append(header)

            detail_rows = [
                [Paragraph("CWE", styles["cell_bold"]), Paragraph(
                    f"{finding.cwe_id or 'N/A'} — {finding.cwe_name or ''}".strip(), styles["cell"])],
                [Paragraph("LOCATION", styles["cell_bold"]), Paragraph(file_loc, styles["cell"])],
                [Paragraph("CONFIDENCE", styles["cell_bold"]), Paragraph(
                    f"{confidence}% (AI-evaluated)" if confidence else "Not AI-evaluated", styles["cell"])],
                [Paragraph("EXPLANATION", styles["cell_bold"]), Paragraph(
                    _finding_explanation(finding), styles["cell"])],
                [Paragraph("REMEDIATION", styles["cell_bold"]), Paragraph(
                    _finding_remediation(finding), styles["cell"])],
            ]
            if finding.code_snippet:
                snippet = finding.code_snippet.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                detail_rows.append([Paragraph("CODE", styles["cell_bold"]), Paragraph(
                    f"<font face='Courier' size='7'>{snippet[:600]}</font>", styles["cell"])])
            detail_table = Table(detail_rows, colWidths=[30 * mm, None])
            detail_table.setStyle(TableStyle([
                ("GRID", (0, 0), (-1, -1), 0.5, BLACK),
                ("BACKGROUND", (0, 0), (0, -1), LIGHT),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ]))
            story.append(detail_table)
            story.append(Spacer(1, 4 * mm))
            if idx % 3 == 0 and idx != len(findings):
                story.append(PageBreak())

    # ── 07 Timeline ─────────────────────────────────────────────────────────
    story.append(PageBreak())
    story.extend(_section_header("Timeline", styles, 7))
    timeline_rows = [[
        Paragraph("STAGE", styles["cell_bold"]),
        Paragraph("STATUS", styles["cell_bold"]),
        Paragraph("TIMESTAMP", styles["cell_bold"]),
    ]]
    for entry in assessment.timeline or []:
        timeline_rows.append([
            Paragraph(str(entry.get("step", "")).replace("_", " ").title(), styles["cell"]),
            Paragraph(str(entry.get("status", "")).upper(), styles["cell"]),
            Paragraph(str(entry.get("timestamp", "")).replace("T", " ")[:19], styles["cell"]),
        ])
    if len(timeline_rows) == 1:
        timeline_rows.append([Paragraph("—", styles["cell"]), Paragraph("—", styles["cell"]), Paragraph("—", styles["cell"])])
    timeline_table = Table(timeline_rows, colWidths=[55 * mm, 35 * mm, None])
